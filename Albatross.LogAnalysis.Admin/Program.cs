using Albatross.CommandLine;
using Albatross.CommandLine.Defaults;
using Albatross.Config;
using Albatross.LogAnalysis.Admin.AutoGenerated;
using Albatross.LogAnalysis.Admin.Config;
using Albatross.LogAnalysis.Admin.Services;
using Albatross.LogAnalysis.Database.Postgres;
using Albatross.LogAnalysis.Database.SqlServer;
using Albatross.LogAnalysis.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.DependencyInjection.Extensions;
using Microsoft.Extensions.Hosting;
using System.CommandLine;
using System.Threading.Tasks;

namespace Albatross.LogAnalysis.Admin {
	class Program {
		static async Task<int> Main(string[] args) {
			Albatross.Logging.Extensions.RemoveLegacySlackSinkOptions();
			if (EF.IsDesignTime) {
				await new HostBuilder().Build().RunAsync();
				return 0;
			}
			await using var host = new CommandHost("Log Analysis Admin")
				.RegisterServices(RegisterServices)
				.AddCommands()
				.Parse(args)
				.WithConfig()
				.WithSerilog()
				.Build();
			return await host.InvokeAsync();
		}

		static void RegisterServices(ParseResult result, IServiceCollection services) {
			services.RegisterCommands();
			services.AddConfig<AdminConfig>();
			services.AddConfig<IAnalysisDbConfig, AdminConfig>();
			services.TryAddSingleton<IAdminConfigService, AdminConfigService>();
			services.TryAddSingleton<IDatabaseService, DatabaseService>();
			services.TryAddScoped<IAnalysisDbSession>(provider => {
				AdminConfig config = provider.GetRequiredService<AdminConfig>();
				if (config.GetDatabaseProvider() == Constants.SqlServerProvider) {
					DbContextOptionsBuilder<AnalysisSqlServerDbSession> optionBuilder = new DbContextOptionsBuilder<AnalysisSqlServerDbSession>();
					Albatross.EFCore.SqlServer.Extensions.BuildSqlServerDbContext(optionBuilder, config.RequiredConnectionString, provider, false);
					return new AnalysisSqlServerDbSession(optionBuilder.Options);
				} else {
					DbContextOptionsBuilder<AnalysisPostgresDbSession> optionBuilder = new DbContextOptionsBuilder<AnalysisPostgresDbSession>();
					Albatross.EFCore.PostgreSQL.Extensions.BuildPostgresDbContext(optionBuilder, config.RequiredConnectionString, provider, false);
					return new AnalysisPostgresDbSession(optionBuilder.Options);
				}
			});
		}
	}
}