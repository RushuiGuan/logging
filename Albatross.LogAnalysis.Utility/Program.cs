using Albatross.CommandLine;
using Albatross.CommandLine.Defaults;
using Albatross.Config;
using Albatross.LogAnalysis.Client;
using Albatross.LogAnalysis.Utility.AutoGenerated;
using Microsoft.Extensions.DependencyInjection;
using System.CommandLine;
using System.Threading.Tasks;

namespace Albatross.LogAnalysis.Utility {
	class Program {
		static async Task<int> Main(string[] args) {
			await using var host = new CommandHost("Log Analysis Cli")
				.RegisterServices(RegisterServices)
				.AddCommands()
				.Parse(args)
				.WithConfig()
				.WithSerilog()
				.Build();
			return await host.InvokeAsync();
		}

		static void RegisterServices(ParseResult result, IServiceCollection services) {
			services.RegisterCommands();
			services.AddConfig<UtilityConfig>();
			services.AddConfig<ILogAnalysisClientConfig, UtilityConfig>();
			services.AddLogAnalysisClient();
		}
	}
}